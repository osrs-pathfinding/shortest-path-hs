#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i], process.argv[i + 1]);

const resources = args.get("--resources") || "../shortest-path/src/main/resources/transports";
const varbitFile = args.get("--varbit") || "../runelite/runelite-api/src/main/java/net/runelite/api/gameval/VarbitID.java";
const varPlayerFile = args.get("--varplayer") || "../runelite/runelite-api/src/main/java/net/runelite/api/gameval/VarPlayerID.java";
const output = args.get("--output") || "data/gamevars";
const haskell = args.get("--haskell") || "src/ShortestPath/GameVars";
const revision = args.get("--revision");

if (!revision) fail("--revision is required; pin the RuneLite gameval source revision");

const mappings = {
  varbit: parseMapping(varbitFile),
  varplayer: parseMapping(varPlayerFile),
};
const rows = [];

for (const file of fs.readdirSync(resources).filter(name => name.endsWith(".tsv")).sort()) {
  const lines = fs.readFileSync(path.join(resources, file), "utf8").split(/\r?\n/);
  const header = lines.find(line => line.startsWith("# "))?.slice(2).split("\t") || [];
  const varbitColumn = header.indexOf("Varbits");
  const varplayerColumn = header.indexOf("VarPlayers");
  if (varbitColumn < 0 && varplayerColumn < 0) continue;
  for (let lineNumber = 0; lineNumber < lines.length; lineNumber++) {
    const line = lines[lineNumber];
    if (!line || line.startsWith("#")) continue;
    const fields = line.split("\t");
    for (const [kind, column] of [["varbit", varbitColumn], ["varplayer", varplayerColumn]]) {
      if (column < 0) continue;
      for (const requirement of (fields[column] || "").split(";").filter(Boolean)) {
        const match = requirement.match(/^(\d+)(=|>|<|&|@)(\d+)$/);
        if (!match) continue;
        const id = Number(match[1]);
        const name = mappings[kind].get(id);
        rows.push({ kind, id, name: name || "UNMAPPED", operator: match[2], value: Number(match[3]), file, line: lineNumber + 1, requirement });
      }
    }
  }
}

const unique = new Map();
for (const row of rows) {
  const key = `${row.kind}:${row.id}`;
  const existing = unique.get(key) || { kind: row.kind, id: row.id, name: row.name, requirements: new Set(), uses: [] };
  existing.requirements.add(`${row.operator}${row.value}`);
  existing.uses.push(`${row.file}:${row.line} ${row.requirement}`);
  unique.set(key, existing);
}

for (const row of unique.values()) {
  if (row.name === "UNMAPPED") fail(`no RuneLite semantic name for ${row.kind} ${row.id}`);
}

fs.mkdirSync(output, { recursive: true });
fs.mkdirSync(haskell, { recursive: true });
const sorted = [...unique.values()].sort((a, b) => a.kind.localeCompare(b.kind) || a.id - b.id);
const audit = ["kind\tid\tname\trequirements\tuses\tsources", ...sorted.map(row => [row.kind, row.id, row.name, [...row.requirements].sort().join(";"), row.uses.length, row.uses.join(" | ")].join("\t"))];
fs.writeFileSync(path.join(output, "transport-gamevars.tsv"), audit.join("\n") + "\n");
fs.writeFileSync(path.join(output, "runelite-revision.txt"), revision + "\n");
  writeModule("Varbits", "VarbitId", "VarbitId", sorted.filter(row => row.kind === "varbit"));
  writeModule("VarPlayers", "VarPlayerId", "VarPlayerId", sorted.filter(row => row.kind === "varplayer"));
console.log(`generated ${sorted.filter(row => row.kind === "varbit").length} varbits and ${sorted.filter(row => row.kind === "varplayer").length} varplayers`);

function parseMapping(file) {
  const result = new Map();
  for (const match of fs.readFileSync(file, "utf8").matchAll(/public static final int ([A-Z0-9_]+) = (\d+);/g)) result.set(Number(match[2]), match[1]);
  return result;
}

function writeModule(module, type, constructor, entries) {
  const names = entries.map(row => [haskellName(row.name), row]);
  const body = [`-- Generated by scripts/generate-gamevars.js; do not edit.`, `module ShortestPath.GameVars.${module}`, `  ( ${names.map(([name]) => name).join("\n  , ")}`, `  , ${module === "Varbits" ? "varbitName" : "varPlayerName"}`, `  ) where`, ``, `import qualified Data.Map.Strict as Map`, `import ShortestPath.GameVars (${type}(..))`, ``, ...names.map(([name, row]) => `${name} :: ${type}\n${name} = ${constructor} ${row.id}`), ``, `${module === "Varbits" ? "varbitName" : "varPlayerName"} :: ${type} -> Maybe String`, `${module === "Varbits" ? "varbitName" : "varPlayerName"} value = Map.lookup value names`, ``, `names :: Map.Map ${type} String`, `names = Map.fromList` , `  [ ${names.map(([name, row]) => `(${name}, "${row.name}")`).join("\n  , ")}`, `  ]`, ""].join("\n");
  fs.writeFileSync(path.join(haskell, `${module}.hs`), body);
}

function haskellName(name) {
  return name.toLowerCase().replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
